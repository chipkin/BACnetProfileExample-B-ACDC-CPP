// BACnet Profile Example - B-ACDC (Access Control Door Controller) - C++
//
// This example implements the BACnet "B-ACDC" (Access Control Door Controller)
// device profile with the CAS BACnet Stack. It is the B-SS (Smart Sensor)
// example plus the one thing that makes a door controller: an Access Door object
// that a client can LOCK and UNLOCK with WriteProperty.
//
// A B-ACDC (ANSI/ASHRAE 135, Annex L.7 - Miscellaneous) is a small, focused
// device. Its mandatory capabilities are:
//
//     DS-RP-B    - respond to ReadProperty requests (like B-SS)
//     DS-WP-B    - allow other devices to WriteProperty its objects
//     DS-ACAD-B  - present an Access Door object whose Present_Value is
//                  readable and writable (this is the profile's defining BIBB)
//     DM-DDB-B   - answer Who-Is with I-Am        (handled by the stack)
//     DM-DOB-B   - answer Who-Has with I-Have     (handled by the stack)
//
// A B-ACDC requires NO alarms/events, NO scheduling, NO trending, and NO COV -
// so this example deliberately does not enable any of them. That is the whole
// point of a profile example: implement exactly what the profile asks for,
// nothing more. (A door controller that ALSO reports access events is a
// B-ACC / B-AACC - a different, larger profile with its own example.) The door
// still KNOWS when it is in trouble - its Door_Alarm_State property reads
// forcedOpen or doorOpenTooLong - it just does not send event notifications
// about it.
//
// THE PROFILE FUNCTION - what makes this a door controller and not just a device
// with a door-shaped object - is in section 1b, "The door Simulation", and the
// tick in main(): a lock relay that follows the commanded Present_Value, a
// door-position contact, pulse unlocks that RE-LOCK on their own after
// Door_Pulse_Time (clause 12.26.4 / 12.26.16), and the two classic door alarms,
// forced open and held open too long (12.26.19 / 12.26.20). The relay and the
// contact are SIMULATION: on a real controller they are a GPIO output and a GPIO
// input; everything BACnet does with them is real.
//
// The device keeps the three read-only sensor objects from B-SS and adds the one
// object this profile exists for. Each object has a colour name (the convention
// shared across this example series):
//
//     Device 389011          "Chipkin Example B-ACDC"    (instance configurable with --deviceID)
//     Analog Input  1        "Bronze"     (REAL, degrees Celsius; read-only)
//     Binary Input  1        "Emerald"    (active / inactive; read-only)
//     Multi-State Input 1    "Hot Pink"   (state 1..3; read-only)
//     Access Door 1          "Cobalt"     (lock / unlock / pulse; commandable, re-locks itself)
//     Network Port 1         "Vermilion"  (the BACnet/IP port - required)
//
// THE ACCESS DOOR IS COMMANDABLE. This is the key thing to understand, and it is
// the same mechanism the B-SA (Smart Actuator) example uses for its outputs: the
// door's Present_Value is NOT stored directly. It is resolved by the stack from a
// 16-slot BACnet Priority_Array plus a Relinquish_Default. A
// WriteProperty(Present_Value, value, priority) sets a slot; writing NULL
// relinquishes it; the stack reports the highest-priority non-null slot (or
// Relinquish_Default) as the effective Present_Value. The application stores the
// array (see the Commandable struct below) and serves it; the stack computes
// Present_Value from it. Because a door is life-safety-adjacent hardware, this
// priority mechanism is exactly what you want: a fire-alarm system can command
// the door at a high priority and a badge reader at a low one, and BACnet
// resolves who wins.
//
// To be a conformant BACnet device (Protocol_Revision 30) each object must
// expose its full set of REQUIRED properties. Most are generated by the stack
// (Object_Identifier, Object_Type, Status_Flags, Object_List, Protocol_*).
// Event_State is NOT generated - with no alarming configured it simply reads its
// datatype default of normal(0), correct by coincidence, not because the stack
// computes it. Reliability is the same story: this example serves it explicitly
// below (GetPropertyEnumerated), but the value it serves - noFaultDetected(0) - is
// also the datatype default, so it reads correctly either way. The handful the
// application must supply are served by
// the Get*Property callbacks below. Note that an Access Door has three REQUIRED
// timing properties that no other object in this series has - Door_Pulse_Time,
// Door_Extended_Pulse_Time, and Door_Open_Too_Long_Time - and this example serves
// all three.
//
// Interactive keys (read by the shared helper): h = help, q = quit,
// up/down = nudge Analog Input 1 by +/-1.1, and the door Simulation's keys:
// o = open / close the door, f = force the door open, p = present a badge (a
// local pulseUnlock at priority 8). Command line: --port <n>, --deviceID <n>.
//
// All the UDP/stack plumbing lives in common/CASExampleHelper so this file can
// stay focused on the BACnet logic.
// =============================================================================

